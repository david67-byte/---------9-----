#include <iostream>

using namespace std;

const int MAXN = 1005; // Максимальное количество пирожков + запас
int N, D;              // N - кол-во пирожков, D - кол-во дней
int a[MAXN];           // Массив для хранения калорийности

// ФУНКЦИЯ ПРОВЕРКИ: 
// Отвечает на вопрос "Можно ли разбить пирожки на дни так, 
// чтобы разница между самым жирным и самым легким в каждом дне не превышала X?"
bool canAchieve(int X) {
    int days_needed = 1;           // Минимум 1 день нам понадобится
    int current_day_min = a[0];    // Запоминаем калорийность первого пирожка в текущем дне

    // Проходим по всем пирожкам (они уже отсортированы по возрастанию)
    for (int i = 1; i < N; ++i) {
        // Если разница между текущим пирожком и самым легким в этом дне превышает X...
        if (a[i] - current_day_min > X) {
            days_needed++;             // ...то текущий день закончен, начинаем новый
            current_day_min = a[i];    // Текущий пирожок становится первым (и пока самым легким) в новом дне
        }
    }
    
    // Если мы уложились в заданное количество дней D, значит такой X нам подходит
    return days_needed <= D;
}

int main() {
    // Считываем количество пирожков и количество дней
    cin >> N >> D;
    for (int i = 0; i < N; ++i) {
        cin >> a[i];
    }

    // ШАГ 1: Сортируем калорийность по возрастанию (пузырьком, чтобы не подключать <algorithm>)
    for (int i = 0; i < N - 1; ++i) {
        for (int j = 0; j < N - i - 1; ++j) {
            if (a[j] > a[j + 1]) {
                // Меняем местами, если предыдущий больше следующего
                int temp = a[j];
                a[j] = a[j + 1];
                a[j + 1] = temp;
            }
        }
    }

    // ШАГ 2: Бинарный поиск минимальной разницы
    int left = 0;                       // Минимально возможная разница (все пирожки одинаковые)
    int right = a[N - 1] - a[0];        // Максимально возможная разница (между самым жирным и самым легким за все дни)
    int ans = right;                    // Изначально считаем, что ответ - это худший вариант

    while (left <= right) {
        int mid = left + (right - left) / 2; // Берем середину диапазона
        
        if (canAchieve(mid)) {
            // Если разница 'mid' подходит, запоминаем её...
            ans = mid;      
            // ...и пытаемся найти еще меньшую разницу (сдвигаем правую границу влево)
            right = mid - 1;
        } else {
            // Если разница 'mid' слишком маленькая (не хватает дней), нужно ее увеличить
            left = mid + 1; 
        }
    }

    // Выводим минимальную найденную разницу
    cout << ans << endl;

    return 0;
}