#include <iostream>

using namespace std;

int main() {
    int N, K, L;
    // N - всего растений, K - нужно в букет, L - лимит на одинаковые
    cin >> N >> K >> L;
    
    // Массив для хранения стоимости растений
    int a[105];
    for (int i = 0; i < N; ++i) {
        cin >> a[i];
    }

    // ШАГ 1: Сортировка по УБЫВАНИЮ.
    // Нам выгоднее всего брать самые дорогие растения, поэтому ставим их в начало.
    for (int i = 0; i < N - 1; ++i) {
        for (int j = 0; j < N - i - 1; ++j) {
            if (a[j] < a[j + 1]) { // Обратите внимание на знак '<' - это убывание
                int temp = a[j];
                a[j] = a[j + 1];
                a[j + 1] = temp;
            }
        }
    }

    // ШАГ 2: собираем букет
    int total_sum = 0;           // Итоговая стоимость букета
    int collected = 0;           // Сколько растений мы уже положили в букет
    int current_count = 0;       // Сколько штук текущего вида растения мы уже взяли
    int last_value = -1;         // Стоимость предыдущего взятого растения (для отслеживания)

    // Идем по отсортированному массиву (от самых дорогих к дешевым)
    for (int i = 0; i < N; ++i) {
        // Если набрали нужное количество растений (K), дальше не идем
        if (collected == K) {
            break;
        }

        // Проверяем: такое же ли это растение, как предыдущее?
        if (a[i] == last_value) {
            // Если мы уже взяли максимум таких растений (L), то пропускаем это
            if (current_count == L) {
                continue; // Переходим к следующему (которое будет дешевле)
            }
            current_count++; // Берем еще одно такое же
        } else {
            // Если это растение другого вида, сбрасываем счетчик
            last_value = a[i];
            current_count = 1;
        }

        // Добавляем стоимость к общей сумме и увеличиваем счетчик собранных
        total_sum += a[i];
        collected++;
    }

    // Выводим итоговую максимальную стоимость
    cout << total_sum << endl;

    return 0;
}