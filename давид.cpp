#include <iostream>

using namespace std;

int main() {
    int N, M;
    // Считываем количество строк (N) и столбцов (M)
    cin >> N >> M;

    // Используем одномерный массив для экономии памяти.
    // Размер 1000 взят с запасом, так как точный максимум M не указан, но обычно он не превышает 1000.
    int dp[1000] = {0}; 

    // Проходим по всем строкам лабиринта
    for (int i = 0; i < N; ++i) {
        // Проходим по всем столбцам текущей строки
        for (int j = 0; j < M; ++j) {
            int val;
            cin >> val; // Считываем значение текущей клетки (баллы или штрафы)

            // ЛОГИКА ЗАПОЛНЕНИЯ:
            // 1. Самая первая клетка (левый верхний угол) - это старт
            if (i == 0 && j == 0) {
                dp[j] = val; 
            } 
            // 2. Если мы в первой строке, но не в первом столбце, 
            // то мы могли прийти сюда ТОЛЬКО слева (двигаясь вправо)
            else if (i == 0) {
                dp[j] = dp[j - 1] + val; 
            } 
            // 3. Если мы в первом столбце, но не в первой строке, 
            // то мы могли прийти сюда ТОЛЬКО сверху (двигаясь вниз)
            else if (j == 0) {
                dp[j] = dp[j] + val; 
            } 
            // 4. Для всех остальных клеток мы выбираем лучший путь:
            // dp[j] (значение сверху) или dp[j-1] (значение слева). 
            // Берем то, что больше, и прибавляем текущую клетку.
            else {
                // Тернарный оператор заменяет функцию max() из библиотеки <algorithm>
                int best_prev = (dp[j] > dp[j - 1]) ? dp[j] : dp[j - 1];
                dp[j] = best_prev + val;
            }
        }
    }

    // Ответ всегда будет накапливаться в последней ячейке (правый нижний угол)
    cout << dp[M - 1] << endl;

    return 0;
}