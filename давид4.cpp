#include <iostream>

using namespace std;

const int MAXN = 105; // Максимальный размер лабиринта
int N, M;             // Размеры лабиринта
char maze[MAXN][MAXN]; // Сам лабиринт
bool visited[MAXN][MAXN]; // Массив для отслеживания посещенных клеток
int max_pdf = -1;     // Максимальное найденное количество файлов (-1 значит, что выхода нет)

// Массивы для движения: Вверх, Вниз, Влево, Вправо
int dr[] = {-1, 1, 0, 0};
int dc[] = {0, 0, -1, 1};

// Рекурсивная функция поиска
// r, c - текущие координаты, collected - сколько P уже собрали
void dfs(int r, int c, int collected) {
    // Если мы наступили на выход (E)
    if (maze[r][c] == 'E') {
        // Если этот путь принес больше файлов, чем все предыдущие - запоминаем
        if (collected > max_pdf) {
            max_pdf = collected; 
        }
        return; // Дальше идти не нужно, мы нашли выход
    }

    // Перебираем 4 возможных направления движения
    for (int i = 0; i < 4; ++i) {
        int nr = r + dr[i]; // Новая координата строки
        int nc = c + dc[i]; // Новая координата столбца

        // Проверяем, не вышли ли мы за пределы лабиринта
        if (nr >= 0 && nr < N && nc >= 0 && nc < M) {
            // Проверяем, что клетка не стена (1) и мы там еще не были
            if (maze[nr][nc] != '1' && !visited[nr][nc]) {
                
                visited[nr][nc] = true; // Отмечаем клетку как посещенную
                
                // Если на новой клетке лежит PDF-файл, добавляем 1 к счетчику
                int add = (maze[nr][nc] == 'P') ? 1 : 0;
                
                // Рекурсивно идем дальше
                dfs(nr, nc, collected + add);
                
                // ВАЖНО: "Откат" (Backtracking). 
                // Мы возвращаем visited в false, чтобы при поиске других путей 
                // мы могли снова зайти в эту клетку из другого направления.
                visited[nr][nc] = false; 
            }
        }
    }
}

int main() {
    cin >> N >> M;

    int start_r = -1, start_c = -1;

    // Читаем лабиринт
    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < M; ++j) {
            cin >> maze[i][j];
        }
    }

    // Ищем стартовую позицию. 
    // Предполагаем, что старт там, где стоит 'P' или пустая клетка '0' (берем первую попавшуюся).
    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < M; ++j) {
            if (maze[i][j] != '1' && maze[i][j] != 'E') {
                start_r = i;
                start_c = j;
                break;
            }
        }
        if (start_r != -1) break;
    }

    // Если стартовая клетка не найдена (что странно), ставим в левый верхний угол
    if (start_r == -1) {
        start_r = 0; 
        start_c = 0;
    }

    // Инициализируем стартовую клетку
    visited[start_r][start_c] = true;
    // Если на старте тоже лежит PDF, считаем его
    int initial_pdf = (maze[start_r][start_c] == 'P') ? 1 : 0;
    
    // Запускаем поиск с нашей стартовой точки
    dfs(start_r, start_c, initial_pdf);

    // Выводим результат
    if (max_pdf == -1) {
        cout << "Выход не найден" << endl;
    } else {
        cout << max_pdf << endl;
    }

    return 0;
}